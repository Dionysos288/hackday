const STEP = 6;

/* the height of a capital is 0.72 of the type size, as the mono face's capitals are */
export const capOf = (size: number) => size * 0.72;
export function strokeWidth(s: string, size: number) { return s.length ? (s.length * STEP - 2) * (capOf(size) / 6) : 0; }

export function strokeText(s: string, x: number, y: number, size: number, align: Align = 'left'): Poly[] {
  const u = capOf(size) / 6, w = strokeWidth(s, size), x0 = align === 'left' ? x : align === 'center' ? x - w / 2 : x - w, top = y - 6 * u;
  const out: Poly[] = [];
  [...s.toUpperCase()].forEach((ch, i) => {
    const g = G[ch]; if (!g) return;
    const ox = x0 + i * STEP * u;
    for (const st of g) { const p: Poly = []; for (let k = 0; k < st.length; k += 2) p.push([ox + st[k] * u, top + st[k + 1] * u]); out.push(p); }
  });
  return out;
}
